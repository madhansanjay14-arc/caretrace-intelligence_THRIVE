/**
 * Deterministic What-If calculation formula:
 * For Sarah Jenkins (P-1042):
 * Base Missed Appointments: 4 -> Base Risk: 87
 * When Missed Appointments changed to 2 -> Projected Risk: 68
 * Difference: 19 points improvement
 *
 * Formula:
 * delta = (simulatedMissed - baseMissed) * pointPerMissed
 * transportationBonus = transportAssistanceProvided ? -12 : 0
 * telehealthBonus = telehealthEnrollment ? -8 : 0
 */
export function calculateSimulatedRisk(
  patient: Patient,
  simulatedMissed: number,
  transportAssistanceProvided: boolean = false,
  telehealthEnrollment: boolean = false
): { projectedRisk: number; improvement: number; projectedLevel: RiskLevel } {
  const baseMissed = patient.missedAppointments;
  const baseRisk = patient.simulatedRisk;

  // Sensitivity weight per missed appointment:
  // For P-1042: (4 - 2) * 9.5 = 19 points -> 87 - 19 = 68 exact match!
  const pointPerMissed = patient.id === 'P-1042' ? 9.5 : 8.5;

  const missedImpact = (simulatedMissed - baseMissed) * pointPerMissed;
  const transportImpact = transportAssistanceProvided ? -12 : 0;
  const telehealthImpact = telehealthEnrollment ? -8 : 0;

  let calculated = Math.round(baseRisk + missedImpact + transportImpact + telehealthImpact);
  // Clamping between 5 and 99
  calculated = Math.max(5, Math.min(99, calculated));

  const improvement = baseRisk - calculated;

  let projectedLevel: RiskLevel = 'LOW';
  if (calculated >= 70) {
    projectedLevel = 'HIGH';
  } else if (calculated >= 40) {
    projectedLevel = 'MEDIUM';
  } else {
    projectedLevel = 'LOW';
  }

  return {
    projectedRisk: calculated,
    improvement,
    projectedLevel,
  };
}

